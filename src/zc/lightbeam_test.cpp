static void test_trigger_sets()
{
	const char* layout = R"(
		................
		................
		................
		................
		................
		..>.............
		................
		................
		................
		................
		................
	)";

	for (int set : {0, 1, 3})
	{
		for_each_source("trigger sets", [&](Source source){
			Trace t = build(layout);
			run(t, source, set);
			int expected = set ? 1 << (set - 1) : ~0;
			int lit = t.world.istrig[(int)COMBOPOS_REGION_INDEX(t.world.region, 9, 5)];
			int unlit = t.world.istrig[(int)COMBOPOS_REGION_INDEX(t.world.region, 9, 6)];
			if (lit != expected || unlit != 0)
				throw std::runtime_error(fmt::format("set {}: lit spot has {:#x} (expected {:#x}), unlit spot has {:#x}",
					set, lit, expected, unlit));
		});
	}
}

