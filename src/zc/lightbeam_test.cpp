TestResults test_lightbeam(bool verbose)
{
	TestResults tr{};
	struct { const char* name; void (*fn)(); } tests[] = {
		{ "straight", test_straight },
		{ "blockers", test_blockers },
		{ "mirrors", test_mirrors },
		{ "prisms", test_prisms },
		{ "custom_mirror", test_custom_mirror },
		{ "light_targets", test_light_targets },
		{ "hero", test_hero },
		{ "loops", test_loops },
		{ "region", test_region },
		{ "no_direction", test_no_direction },
		{ "ffc_positions", test_ffc_positions },
		{ "trigger_sets", test_trigger_sets },
	};

	for (auto& test : tests)
	{
		++tr.total;
		failures = 0;
		test.fn();
		if (failures)
			++tr.failed;
		else if (verbose)
			fmt::println("  [PASS] {}", test.name);
	}

	return tr;
}
